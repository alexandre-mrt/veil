//! Generates a Groth16 proof of the canonical transfer witness, serializes
//! vk / proof / public inputs to the sui::groth16 byte layout, writes hex files
//! to out/, and emits a self-contained Move unit test into
//! move-verify/sources/verify_test.move that calls
//! sui::groth16::verify_groth16_proof with those exact bytes.
//!
//! Run with: cargo run --release --bin export_sui

use ark_bn254::Bn254;
use ark_groth16::Groth16;
use ark_snark::{CircuitSpecificSetupSNARK, SNARK};
use ark_std::rand::rngs::StdRng;
use ark_std::rand::SeedableRng;
use std::fs;
use std::path::Path;

use veil_arkworks_spike::circuit::TransferCircuit;
use veil_arkworks_spike::sui::{proof_to_sui_bytes, public_inputs_to_sui_bytes, vk_to_sui_bytes};
use veil_arkworks_spike::witness::canonical_circuit;

const SETUP_SEED: u64 = 42;

fn main() {
    let mut rng = StdRng::seed_from_u64(SETUP_SEED);
    let (pk, vk) =
        Groth16::<Bn254>::circuit_specific_setup(TransferCircuit::blank(), &mut rng).unwrap();

    let circuit = canonical_circuit();
    let public_inputs = circuit.public_inputs();
    let proof = Groth16::<Bn254>::prove(&pk, circuit, &mut rng).unwrap();
    assert!(
        Groth16::<Bn254>::verify(&vk, &public_inputs, &proof).unwrap(),
        "proof must verify natively before export"
    );

    let vk_hex = hex::encode(vk_to_sui_bytes(&vk));
    let proof_hex = hex::encode(proof_to_sui_bytes(&proof));
    let inputs_hex = hex::encode(public_inputs_to_sui_bytes(&public_inputs));

    let root = Path::new(env!("CARGO_MANIFEST_DIR"));
    let out = root.join("out");
    fs::create_dir_all(&out).unwrap();
    fs::write(out.join("vk.hex"), &vk_hex).unwrap();
    fs::write(out.join("proof.hex"), &proof_hex).unwrap();
    fs::write(out.join("public_inputs.hex"), &inputs_hex).unwrap();

    println!("vk            ({} bytes): {}", vk_hex.len() / 2, vk_hex);
    println!("proof         ({} bytes): {}", proof_hex.len() / 2, proof_hex);
    println!("public inputs ({} bytes): {}", inputs_hex.len() / 2, inputs_hex);

    // Emit the Move unit test with the bytes embedded.
    let move_test = format!(
        r#"// AUTO-GENERATED by `cargo run --release --bin export_sui` — do not edit.
// Proof produced by ark-groth16 0.5 (BN254) over the arkworks reimplementation
// of circuits/transfer.circom; verified here by sui::groth16.
#[test_only]
module ark_verify::verify_test {{
    use sui::groth16;

    const VK_BYTES: vector<u8> = x"{vk_hex}";
    const PUBLIC_INPUTS: vector<u8> = x"{inputs_hex}";
    const PROOF: vector<u8> = x"{proof_hex}";

    #[test]
    fun test_arkworks_proof_verifies_on_sui() {{
        let curve = groth16::bn254();
        let pvk = groth16::prepare_verifying_key(&curve, &VK_BYTES);
        let inputs = groth16::public_proof_inputs_from_bytes(PUBLIC_INPUTS);
        let proof = groth16::proof_points_from_bytes(PROOF);
        assert!(groth16::verify_groth16_proof(&curve, &pvk, &inputs, &proof), 0);
    }}

    #[test]
    fun test_tampered_public_input_rejected() {{
        let curve = groth16::bn254();
        let pvk = groth16::prepare_verifying_key(&curve, &VK_BYTES);
        // Flip one bit in epochId (4th public input, bytes 96..128)
        let mut tampered = PUBLIC_INPUTS;
        let byte = tampered.borrow_mut(96);
        *byte = *byte ^ 1;
        let inputs = groth16::public_proof_inputs_from_bytes(tampered);
        let proof = groth16::proof_points_from_bytes(PROOF);
        assert!(!groth16::verify_groth16_proof(&curve, &pvk, &inputs, &proof), 1);
    }}
}}
"#
    );
    let move_sources = root.join("move-verify").join("sources");
    fs::create_dir_all(&move_sources).unwrap();
    fs::write(move_sources.join("verify_test.move"), move_test).unwrap();
    println!("wrote move-verify/sources/verify_test.move");
}
