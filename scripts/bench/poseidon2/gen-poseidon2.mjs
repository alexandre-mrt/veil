#!/usr/bin/env node
// Generates poseidon2_bn254_t3.circom from the HorizenLabs reference constants
// (poseidon2_instance_bn256.rs, t=3, d=5, R_F=8, R_P=56). Usage:
//   node gen-poseidon2.mjs <path/to/poseidon2_instance_bn256.rs> > poseidon2_bn254_t3.circom
import { readFileSync } from "fs";
const src = readFileSync(process.argv[2], "utf8");
const hexes = (name) => {
  const start = src.indexOf(`pub static ref ${name}`);
  const end = src.indexOf("];\n", src.indexOf("vec![", start) ) ;
  const body = src.slice(start, src.indexOf("pub static ref", start + 10) > 0 && name !== "POSEIDON2_BN256_PARAMS" ? src.indexOf("pub static ref", start + 10) : src.length);
  return [...body.matchAll(/from_hex\("0x([0-9a-fA-F]+)"\)/g)].map((m) => BigInt("0x" + m[1]));
};
const rc = hexes("RC3");
if (rc.length !== 64 * 3) throw new Error("expected 192 round constants, got " + rc.length);
const diag = hexes("MAT_DIAG3_M_1");
if (diag.length !== 3) throw new Error("diag");
const RF = 8, RP = 56;
console.log(`pragma circom 2.0.0;
// GENERATED by gen-poseidon2.mjs — Poseidon2 permutation, BN254 Fr, t=3, x^5, R_F=${RF}, R_P=${RP}.
template Sbox5() { signal input in; signal output out; signal s2; signal s4; s2 <== in*in; s4 <== s2*s2; out <== s4*in; }
// external matrix M_E for t=3 = circ(2,1,1) after initial M_E application: y = M_E x
template MExt() { signal input in[3]; signal output out[3]; var s = in[0]+in[1]+in[2]; for (var i=0;i<3;i++) out[i] <== s + in[i]; }
// internal matrix M_I = ones + diag(1,1,2): y_i = sum + d_i*x_i
template MInt() { signal input in[3]; signal output out[3]; var s = in[0]+in[1]+in[2];
  out[0] <== s + ${diag[0]}*in[0]; out[1] <== s + ${diag[1]}*in[1]; out[2] <== s + ${diag[2]}*in[2]; }
template Poseidon2T3() {
  signal input in[3]; signal output out[3];
  var RC[${rc.length}] = [${rc.join(",")}];
  component m0 = MExt(); for (var i=0;i<3;i++) m0.in[i] <== in[i];
  signal st[${RF + RP + 1}][3];
  for (var i=0;i<3;i++) st[0][i] <== m0.out[i];
  component sb[${RF}][3]; component me[${RF}]; component sp[${RP}]; component mi[${RP}];
  var fi = 0; var pi = 0;
  for (var r=0; r<${RF + RP}; r++) {
    if (r < ${RF / 2} || r >= ${RF / 2 + RP}) {
      me[fi] = MExt();
      for (var i=0;i<3;i++) { sb[fi][i] = Sbox5(); sb[fi][i].in <== st[r][i] + RC[r*3+i]; me[fi].in[i] <== sb[fi][i].out; }
      for (var i=0;i<3;i++) st[r+1][i] <== me[fi].out[i];
      fi++;
    } else {
      sp[pi] = Sbox5(); mi[pi] = MInt();
      sp[pi].in <== st[r][0] + RC[r*3];
      mi[pi].in[0] <== sp[pi].out; mi[pi].in[1] <== st[r][1]; mi[pi].in[2] <== st[r][2];
      for (var i=0;i<3;i++) st[r+1][i] <== mi[pi].out[i];
      pi++;
    }
  }
  for (var i=0;i<3;i++) out[i] <== st[${RF + RP}][i];
}
`);
