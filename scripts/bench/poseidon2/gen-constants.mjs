#!/usr/bin/env node
/**
 * gen-constants.mjs — extract the Poseidon2 BN254 t=3 parameters from the HorizenLabs reference
 * implementation and emit them as (a) a JSON file for the JS reference and (b) a circom include.
 *
 * Usage:
 *   git clone --depth 1 https://github.com/HorizenLabs/poseidon2 /tmp/poseidon2   # commit 055bde3f
 *   node scripts/bench/poseidon2/gen-constants.mjs /tmp/poseidon2/plain_implementations/src/poseidon2/poseidon2_instance_bn256.rs
 *
 * Writes:
 *   scripts/bench/poseidon2/constants_bn254_t3.json
 *   circuits/research/poseidon2_constants.circom
 */
import { readFileSync, writeFileSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const src = readFileSync(process.argv[2], "utf8");

const rcBlock = src.split("pub static ref RC3")[1].split("];\n")[0];
const hex = [...rcBlock.matchAll(/from_hex\("(0x[0-9a-fA-F]+)"\)/g)].map((m) => BigInt(m[1]));
if (hex.length !== 64 * 3) throw new Error(`expected 192 round constants, got ${hex.length}`);
const rc = [];
for (let r = 0; r < 64; r++) rc.push(hex.slice(r * 3, r * 3 + 3));

// Sanity: the params line must say t=3, d=5, R_F=8, R_P=56.
if (!/Poseidon2Params::new\(3, 5, 8, 56/.test(src)) throw new Error("unexpected parameter line");

const json = { t: 3, d: 5, rf: 8, rp: 56, rc: rc.map((r) => r.map((x) => x.toString())) };
writeFileSync(join(__dirname, "constants_bn254_t3.json"), JSON.stringify(json, null, 1) + "\n");

// Partial rounds only use rc[r][0]; full rounds use all three.
let circom = `pragma circom 2.1.0;\n\n// AUTO-GENERATED by scripts/bench/poseidon2/gen-constants.mjs from HorizenLabs/poseidon2\n// (plain_implementations/src/poseidon2/poseidon2_instance_bn256.rs, commit 055bde3f).\n// Poseidon2 BN254, t=3, d=5, R_F=8, R_P=56. Do not edit by hand.\n\nfunction POSEIDON2_T3_RC(r, i) {\n    var rc[64][3] = [\n`;
circom += rc.map((r) => `        [${r.map((x) => x.toString()).join(", ")}]`).join(",\n");
circom += `\n    ];\n    return rc[r][i];\n}\n`;
writeFileSync(join(__dirname, "..", "..", "..", "circuits", "research", "poseidon2_constants.circom"), circom);
console.log(`wrote 64x3 round constants (first = 0x${rc[0][0].toString(16)})`);
