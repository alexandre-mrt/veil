#!/usr/bin/env node
/**
 * gen-constants.mjs — emit circuits-side Poseidon2 round constants for BN254.
 *
 * t=3 constants: HorizenLabs/poseidon2 `poseidon2_instance_bn256.rs` (RC3, RF=8, RP=56, d=5),
 *   fetched from raw.githubusercontent.com (path given by --horizen-rs).
 * t=4 constants: the @zkpassport/poseidon2 npm package (RC4 / MAT_DIAG4_M_1, RF=8, RP=56, d=5).
 *
 * Usage: node gen-constants.mjs --horizen-rs <inst.rs> --zkp-constants <.../bn254/constants.js> --out poseidon2_consts.circom
 */
import { readFileSync, writeFileSync } from "fs";
const arg = (n) => process.argv[process.argv.indexOf(n) + 1];
const hexes = (s) => [...s.matchAll(/0x[0-9a-fA-F]{64}/g)].map((m) => BigInt(m[0]).toString());

const rs = readFileSync(arg("--horizen-rs"), "utf8");
const rc3 = hexes(rs.slice(rs.indexOf("RC3"), rs.indexOf("POSEIDON2_BN256_PARAMS")));
if (rc3.length !== 64 * 3) throw new Error(`RC3 count ${rc3.length}`);
const diag3 = hexes(rs.slice(rs.indexOf("MAT_DIAG3_M_1"), rs.indexOf("MAT_INTERNAL3")));

const js = readFileSync(arg("--zkp-constants"), "utf8");
const sec = (a, b) => js.slice(js.indexOf(a), b ? js.indexOf(b) : undefined);
const diag4 = hexes(sec("const MAT_DIAG4_M_1", "const MAT_INTERNAL4"));
const rc4 = hexes(sec("const RC4"));
if (rc4.length !== 64 * 4 || diag4.length !== 4) throw new Error(`RC4 ${rc4.length} diag4 ${diag4.length}`);

const rows = (a, w) => "[" + Array.from({ length: a.length / w }, (_, r) => "[" + a.slice(r * w, r * w + w).join(",") + "]").join(",\n  ") + "]";
const out = `pragma circom 2.1.0;
// GENERATED by scripts/bench/poseidon2/gen-constants.mjs — do not edit. Poseidon2 / BN254, d=5, RF=8, RP=56.
function p2rc3(r, i) { var rc[64][3] = ${rows(rc3, 3)};
  return rc[r][i]; }
function p2diag3(i) { var d[3] = [${diag3.join(",")}]; return d[i]; }
function p2rc4(r, i) { var rc[64][4] = ${rows(rc4, 4)};
  return rc[r][i]; }
function p2diag4(i) { var d[4] = [${diag4.join(",")}]; return d[i]; }
`;
writeFileSync(arg("--out"), out);
console.log(`wrote ${arg("--out")}: ${rc3.length} t=3 + ${rc4.length} t=4 round constants`);
