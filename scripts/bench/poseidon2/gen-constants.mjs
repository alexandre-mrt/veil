#!/usr/bin/env node
/**
 * gen-constants.mjs — extract Poseidon2/BN254 constants (data only, nothing from the sources is
 * executed) into circuits/experiments/poseidon2/constants.circom and a JSON file for the JS reference.
 *
 *   node scripts/bench/poseidon2/gen-constants.mjs <HorizenLabs/poseidon2 checkout> <@zkpassport/poseidon2 unpacked package dir>
 *
 * Provenance (2026-11-08 run):
 *   t=3: HorizenLabs/poseidon2 @ 055bde3f4782731ba5f5ce5888a440a94327eaf3,
 *        plain_implementations/src/poseidon2/poseidon2_instance_bn256.rs (RC3, d=5, R_F=8, R_P=56)
 *   t=4: npm @zkpassport/poseidon2 0.6.2, dist/esm/bn254/constants.js (RC4, MAT_DIAG4_M_1, d=5, R_F=8, R_P=56)
 */
import { readFileSync, writeFileSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const [hz, zkp] = process.argv.slice(2);
if (!hz || !zkp) { console.error("usage: gen-constants.mjs <hz-checkout> <zkpassport-package-dir>"); process.exit(1); }
const hexes = (s) => [...s.matchAll(/0x[0-9a-fA-F]{64}/g)].map((m) => BigInt(m[0]));
const chunk = (a, n) => Array.from({ length: a.length / n }, (_, i) => a.slice(i * n, (i + 1) * n));

const rs = readFileSync(join(hz, "plain_implementations/src/poseidon2/poseidon2_instance_bn256.rs"), "utf8");
const rc3 = chunk(hexes(rs.slice(rs.indexOf("RC3"), rs.indexOf("POSEIDON2_BN256_PARAMS"))), 3);
const diag3 = hexes(rs.slice(rs.indexOf("MAT_DIAG3_M_1"), rs.indexOf("MAT_INTERNAL3")));

const js = readFileSync(join(zkp, "dist/esm/bn254/constants.js"), "utf8");
const rc4 = chunk(hexes(js.slice(js.indexOf("const RC4"), js.indexOf("export"))), 4);
const diag4 = hexes(js.slice(js.indexOf("MAT_DIAG4_M_1"), js.indexOf("const MAT_INTERNAL4")));
if (rc3.length !== 64 || rc4.length !== 64 || diag3.length !== 3 || diag4.length !== 4) throw new Error("unexpected constant shape");

const out = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "..", "circuits", "experiments", "poseidon2");
const arr = (rows) => "[" + rows.map((r) => "[" + r.map((x) => x.toString()).join(",") + "]").join(",\n  ") + "]";
writeFileSync(join(out, "constants.circom"),
`pragma circom 2.1.0;
// GENERATED by scripts/bench/poseidon2/gen-constants.mjs — do not edit. See that file for provenance.
function P2_RC3() { var rc[64][3] = ${arr(rc3)};
  return rc; }
function P2_RC4() { var rc[64][4] = ${arr(rc4)};
  return rc; }
function P2_DIAG4() { var d[4] = [${diag4.join(",")}]; return d; }
`);
writeFileSync(join(out, "constants.json"), JSON.stringify({ rc3, rc4, diag3, diag4 }, (_, v) => typeof v === "bigint" ? v.toString() : v));
console.log("rc3", rc3.length, "rc4", rc4.length, "diag3", diag3.join(","), "diag4", diag4.length);
