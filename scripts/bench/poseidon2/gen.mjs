// Generates circuits/build-p2/ : Poseidon2(t=3) template + transfer/compliance variants whose ONLY
// change is the 2-to-1 Merkle node hash (circomlib Poseidon(2) -> Poseidon2 compress). Production
// circuits are never modified.
import { readFileSync, writeFileSync, mkdirSync, symlinkSync, existsSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";
const here = dirname(fileURLToPath(import.meta.url));
const CIRC = join(here, "..", "..", "..", "circuits");
const OUT = join(CIRC, "build-p2src");
const C = JSON.parse(readFileSync(join(here, "constants-bn254-t3.json"), "utf8"));
mkdirSync(join(OUT, "templates"), { recursive: true });

const L = [];
L.push(`pragma circom 2.1.0;
// Poseidon2 t=3 (x^5, R_F=8, R_P=56), BN254. GENERATED by scripts/bench/poseidon2/gen.mjs.
template Sbox5() { signal input in; signal output out; signal x2; signal x4; x2 <== in*in; x4 <== x2*x2; out <== x4*in; }
template ExtMix() { signal input in[3]; signal output out[3]; signal s; s <== in[0]+in[1]+in[2];
  out[0] <== in[0]+s; out[1] <== in[1]+s; out[2] <== in[2]+s; }
template IntMix() { signal input in[3]; signal output out[3]; signal s; s <== in[0]+in[1]+in[2];
  out[0] <== in[0]+s; out[1] <== in[1]+s; out[2] <== 2*in[2]+s; }
template Poseidon2T3Perm() {
  signal input in[3]; signal output out[3];
  var RC[64][3] = [${C.rc.map((r) => "[" + r.join(",") + "]").join(",\n")}];
  component m0 = ExtMix(); for (var i=0;i<3;i++) m0.in[i] <== in[i];
  signal st[65][3];
  for (var i=0;i<3;i++) st[0][i] <== m0.out[i];
  component sb[64][3]; component ex[64]; component im[64];
  for (var r=0;r<64;r++) {
    if (r<4 || r>=60) {
      for (var i=0;i<3;i++) { sb[r][i] = Sbox5(); sb[r][i].in <== st[r][i] + RC[r][i]; }
      ex[r] = ExtMix(); for (var i=0;i<3;i++) ex[r].in[i] <== sb[r][i].out;
      for (var i=0;i<3;i++) st[r+1][i] <== ex[r].out[i];
    } else {
      sb[r][0] = Sbox5(); sb[r][0].in <== st[r][0] + RC[r][0];
      im[r] = IntMix(); im[r].in[0] <== sb[r][0].out; im[r].in[1] <== st[r][1]; im[r].in[2] <== st[r][2];
      for (var i=0;i<3;i++) st[r+1][i] <== im[r].out[i];
    }
  }
  for (var i=0;i<3;i++) out[i] <== st[64][i];
}
template Poseidon2Compress() { signal input a; signal input b; signal output out;
  component p = Poseidon2T3Perm(); p.in[0] <== a; p.in[1] <== b; p.in[2] <== 0; out <== p.out[0]; }
`);
writeFileSync(join(OUT, "templates", "poseidon2_t3.circom"), L.join("\n"));

// Merkle variant: copy original, swap the node hasher.
let mp = readFileSync(join(CIRC, "templates", "merkle_proof.circom"), "utf8");
mp = mp.replace('include "../node_modules/circomlib/circuits/poseidon.circom";',
  'include "../node_modules/circomlib/circuits/poseidon.circom";\ninclude "poseidon2_t3.circom";')
  .replace("component hashers[depth];", "component hashers[depth];")
  .replace("hashers[i] = Poseidon(2);", "hashers[i] = Poseidon2Compress();")
  .replace("hashers[i].inputs[0] <==", "hashers[i].a <==").replace("hashers[i].inputs[1] <==", "hashers[i].b <==");
if (!mp.includes("Poseidon2Compress") || !mp.includes("hashers[i].b")) throw new Error("merkle patch failed");
writeFileSync(join(OUT, "templates", "merkle_proof.circom"), mp);
for (const c of ["transfer", "compliance", "withdraw"]) writeFileSync(join(OUT, c + ".circom"), readFileSync(join(CIRC, c + ".circom"), "utf8"));
// standalone hash micro-benchmarks
writeFileSync(join(OUT, "hash_circomlib2.circom"), 'pragma circom 2.1.0;\ninclude "node_modules/circomlib/circuits/poseidon.circom";\ncomponent main = Poseidon(2);\n');
writeFileSync(join(OUT, "hash_poseidon2.circom"), 'pragma circom 2.1.0;\ninclude "templates/poseidon2_t3.circom";\ncomponent main = Poseidon2Compress();\n');
if (!existsSync(join(OUT, "node_modules"))) symlinkSync(join(CIRC, "node_modules"), join(OUT, "node_modules"));
console.log("generated", OUT);
