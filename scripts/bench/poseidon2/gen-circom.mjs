/**
 * gen-circom.mjs — emits circuits/research/poseidon2_constants.circom from bn254_t3_constants.json
 * so the circom template and the JS reference read the exact same round constants.
 *
 *   node scripts/bench/poseidon2/gen-circom.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const C = JSON.parse(readFileSync(join(__dirname, "bn254_t3_constants.json"), "utf8"));
const outDir = join(__dirname, "..", "..", "..", "circuits", "research");
mkdirSync(outDir, { recursive: true });

const rows = C.rc.map((r) => `        [${r.join(", ")}]`).join(",\n");
const src = `pragma circom 2.1.0;

// AUTO-GENERATED by scripts/bench/poseidon2/gen-circom.mjs — do not edit.
// Poseidon2 BN254 t=3 d=5 RF=${C.RF} RP=${C.RP} round constants.
// Source: ${C.source}

function POSEIDON2_T3_RC() {
    return [
${rows}
    ];
}
`;
writeFileSync(join(outDir, "poseidon2_constants.circom"), src);
console.log(`wrote ${join(outDir, "poseidon2_constants.circom")} (${C.rc.length} rounds)`);
