/**
 * poseidon2.mjs — Poseidon2 (BN254, state width t=3) permutation, in JS.
 *
 * Mirrors circuits/templates/poseidon2_bn254_t3.circom exactly: same round
 * constants, same external (circ(2,1,1)) and internal (diag(1,1,2)+J) linear
 * layers, same x^5 S-box, same RF=8/RP=56 round structure, same 2-to-1
 * compression convention (permutation([a, b, 0])[0]).
 *
 * Parameters transcribed from the Poseidon2 reference implementation
 * (https://github.com/HorizenLabs/poseidon2,
 * plain_implementations/src/poseidon2/poseidon2_instance_bn256.rs,
 * POSEIDON2_BN256_PARAMS) and validated against that file's own `kats` test
 * vector (input [0,1,2] -> the OFFICIAL_KAT below) before use anywhere in
 * this repo — see docs/research/2026-09-19-poseidon2-merkle-swap.md.
 *
 * Used by circuit tests (circuits/test/*-poseidon2.test.mjs) to build valid
 * witnesses, and by the bench harness (prove-latency.mjs) to build inputs
 * for the *_poseidon2 circuits, the same way circomlibjs's buildPoseidon()
 * is used for the production circuits.
 */

export const BN254_R = 21888242871839275222246405745257275088548364400416034343698204186575808495617n;

function mod(x) {
  x %= BN254_R;
  return x < 0n ? x + BN254_R : x;
}

function sbox(x) {
  const x2 = mod(x * x);
  const x4 = mod(x2 * x2);
  return mod(x4 * x);
}

// diag(1,1,2) + J, applied for t=3 partial rounds.
function internalLinear3(s) {
  const sum = mod(s[0] + s[1] + s[2]);
  return [mod(s[0] + sum), mod(s[1] + sum), mod(2n * s[2] + sum)];
}

// circ(2,1,1), applied for t=3 full rounds (and the initial linear layer).
function externalLinear3(s) {
  const sum = mod(s[0] + s[1] + s[2]);
  return [mod(s[0] + sum), mod(s[1] + sum), mod(s[2] + sum)];
}

let RC = null;
function loadRoundConstants() {
  if (RC) return RC;
  // Same 64x3 decimal constants embedded in poseidon2_bn254_t3.circom.
  RC = RC_DECIMAL.map((row) => row.map(BigInt));
  return RC;
}

/** Poseidon2 permutation over 3 BN254 field elements (bigints). */
export function poseidon2Permute3(input) {
  const rc = loadRoundConstants();
  const RF = 8;
  const RP = 56;
  const half = RF / 2;

  let state = input.map(mod);
  state = externalLinear3(state);

  for (let round = 0; round < half; round++) {
    state = state.map((v, i) => mod(v + rc[round][i]));
    state = state.map(sbox);
    state = externalLinear3(state);
  }
  for (let round = half; round < half + RP; round++) {
    state[0] = mod(state[0] + rc[round][0]);
    state[0] = sbox(state[0]);
    state = internalLinear3(state);
  }
  for (let round = half + RP; round < RF + RP; round++) {
    state = state.map((v, i) => mod(v + rc[round][i]));
    state = state.map(sbox);
    state = externalLinear3(state);
  }
  return state;
}

/**
 * 2-to-1 compression matching Poseidon2Hash2to1 in
 * poseidon2_bn254_t3.circom and the reference implementation's
 * MerkleTreeHash::compress: permutation([a, b, 0])[0].
 * Accepts bigints or values convertible via BigInt(...).
 */
export function poseidon2Hash2to1(a, b) {
  const out = poseidon2Permute3([BigInt(a), BigInt(b), 0n]);
  return out[0];
}

