#!/usr/bin/env node
// Extracts Poseidon2 (BN254, t=3 and t=4) round constants from @taceo/poseidon2,
// cross-checks the t=4 parameters bit-for-bit against the independently-shipped
// @zkpassport/poseidon2 package, and regenerates circuits/bench/poseidon2.circom.
//
// Why two packages: neither ships the raw constants as public API (both bury them
// in module-internal `var`s), and neither publishes a from-the-paper derivation
// script we can run ourselves without network access to the HorizenLabs repo. Two
// independent implementations agreeing bit-for-bit on t=4 is the only correctness
// signal available in this sandbox — it is NOT a substitute for re-deriving the
// constants from https://github.com/HorizenLabs/poseidon2/blob/main/poseidon2_rust_params.sage
// against the Poseidon2 paper (eprint 2023/323) directly, which a real migration
// would require.
//
// Usage: node scripts/bench/poseidon2-constants.mjs [--check-only]
import fs from "fs";
import { fileURLToPath } from "url";
import path from "path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "..", "..");
const taceoDist = path.join(
  repoRoot,
  "circuits/node_modules/@taceo/poseidon2/dist/index.js"
);
const zkpassportConstants = path.join(
  repoRoot,
  "circuits/node_modules/@zkpassport/poseidon2/dist/esm/bn254/constants.js"
);

function extractArray(src, name) {
  const marker = `var ${name} = `;
  const start = src.indexOf(marker);
  if (start === -1) throw new Error("not found in @taceo/poseidon2 dist: " + name);
  let i = start + marker.length;
  if (src[i] !== "[") throw new Error("expected [ at start for " + name);
  let depth = 0;
  let j = i;
  for (; j < src.length; j++) {
    if (src[j] === "[") depth++;
    else if (src[j] === "]") {
      depth--;
      if (depth === 0) { j++; break; }
    }
  }
  return src.slice(i, j);
}

const taceoSrc = fs.readFileSync(taceoDist, "utf8");
const T3_EXT_RC = JSON.parse(extractArray(taceoSrc, "T3_EXT_RC"));
const T3_INT_RC = JSON.parse(extractArray(taceoSrc, "T3_INT_RC"));
const T4_EXT_RC = JSON.parse(extractArray(taceoSrc, "T4_EXT_RC"));
const T4_INT_RC = JSON.parse(extractArray(taceoSrc, "T4_INT_RC"));
const T4_MAT = JSON.parse(extractArray(taceoSrc, "T4_MAT"));

// --- cross-check t=4 against @zkpassport/poseidon2 (independent implementation) ---
const { MAT_DIAG4_M_1, RC4 } = await import(
  "file://" + zkpassportConstants
);
const zkDiag = MAT_DIAG4_M_1.map(String);
if (JSON.stringify(zkDiag) !== JSON.stringify(T4_MAT)) {
  throw new Error(
    "CROSS-CHECK FAILED: @taceo/poseidon2 T4_MAT != @zkpassport/poseidon2 MAT_DIAG4_M_1"
  );
}
if (RC4.length !== T4_EXT_RC.length + T4_INT_RC.length) {
  throw new Error(
    `CROSS-CHECK FAILED: RC4 has ${RC4.length} rows, expected ${T4_EXT_RC.length + T4_INT_RC.length}`
  );
}
for (let r = 0; r < 4; r++) {
  const got = RC4[r].map(String);
  if (JSON.stringify(got) !== JSON.stringify(T4_EXT_RC[r])) {
    throw new Error(`CROSS-CHECK FAILED: RC4[${r}] != T4_EXT_RC[${r}]`);
  }
}
for (let r = 0; r < 56; r++) {
  const got = String(RC4[4 + r][0]);
  if (got !== T4_INT_RC[r]) {
    throw new Error(`CROSS-CHECK FAILED: RC4[${4 + r}][0] != T4_INT_RC[${r}]`);
  }
}
for (let r = 0; r < 4; r++) {
  const got = RC4[60 + r].map(String);
  if (JSON.stringify(got) !== JSON.stringify(T4_EXT_RC[4 + r])) {
    throw new Error(`CROSS-CHECK FAILED: RC4[${60 + r}] != T4_EXT_RC[${4 + r}]`);
  }
}
console.log(
  "Cross-check OK: @taceo/poseidon2 and @zkpassport/poseidon2 agree bit-for-bit on t=4 " +
    "(diagonal + all 64 rounds' external constants + all 56 internal constants)."
);
console.log(
  "No independent second source exists for t=3 in this sandbox (network access to " +
    "GitHub source repos and to a HorizenLabs/Poseidon2 constant-generation script is " +
    "unavailable) — t=3 constants are taceo-only, single-sourced."
);

if (process.argv.includes("--check-only")) {
  process.exit(0);
}

// circom field-element array literals are bare decimal digits, not quoted
// strings — these values are already decimal-string bigints from the JS
// source, so we splice them in unquoted.
function arr1(vals) {
  return "[" + vals.join(", ") + "]";
}
function arr2(rows) {
  return "[\n" + rows.map((r) => "        " + arr1(r)).join(",\n") + "\n    ]";
}

const generated = `// AUTO-GENERATED by scripts/bench/poseidon2-constants.mjs. Do not hand-edit.
//
// Poseidon2 permutation for BN254, state widths t=3 and t=4, matching the
// canonical HorizenLabs parameterization (RF=8, RP=56, alpha=5, external
// matrix M_E, internal matrix M_I with diag(M4) for t=4 / diag(1,1,2) for
// t=3). Constants extracted from @taceo/poseidon2 0.2.0 (MIT/Apache-2.0),
// which states parity with the HorizenLabs reference sage script and the
// Rust taceo-poseidon2 crate. The t=4 constants are cross-checked bit-for-bit
// against the independently-shipped @zkpassport/poseidon2 package by this
// generator script; t=3 is taceo-only (no second source was reachable).
//
// NOT for production use without an independent from-the-paper re-derivation
// and a second-source audit for t=3. This file exists to measure a
// constraint-count and proving-time delta, not to ship a Poseidon2 migration.
// See docs/research/2026-09-16-poseidon2-microbench.md.
pragma circom 2.1.0;

// ---- t = 3 (2-to-1 compression, matches circomlib Poseidon(2)) ----

function POSEIDON2_T3_EXT_RC() {
    return ${arr2(T3_EXT_RC)};
}

function POSEIDON2_T3_INT_RC() {
    return ${arr1(T3_INT_RC)};
}

template Sigma5() {
    signal input in;
    signal output out;
    signal in2;
    signal in4;
    in2 <== in * in;
    in4 <== in2 * in2;
    out <== in4 * in;
}

// Full Poseidon2 permutation over a 3-element state.
template Poseidon2Perm3() {
    signal input in[3];
    signal output out[3];

    var extRc[8][3] = POSEIDON2_T3_EXT_RC();
    var intRc[56] = POSEIDON2_T3_INT_RC();

    signal state[8 + 56 + 1][3];
    // step 0: initial external mix (no round constants)
    var sum0 = in[0] + in[1] + in[2];
    state[0][0] <== in[0] + sum0;
    state[0][1] <== in[1] + sum0;
    state[0][2] <== in[2] + sum0;

    var idx = 0;

    // first half of full rounds
    signal ark1[4][3];
    component sbF1[4][3];
    for (var r = 0; r < 4; r++) {
        ark1[r][0] <== state[idx][0] + extRc[r][0];
        ark1[r][1] <== state[idx][1] + extRc[r][1];
        ark1[r][2] <== state[idx][2] + extRc[r][2];
        for (var j = 0; j < 3; j++) {
            sbF1[r][j] = Sigma5();
            sbF1[r][j].in <== ark1[r][j];
        }
        var s = sbF1[r][0].out + sbF1[r][1].out + sbF1[r][2].out;
        state[idx+1][0] <== sbF1[r][0].out + s;
        state[idx+1][1] <== sbF1[r][1].out + s;
        state[idx+1][2] <== sbF1[r][2].out + s;
        idx++;
    }

    // partial rounds (S-box on state[0] only)
    signal a0[56];
    component sbP[56];
    for (var r = 0; r < 56; r++) {
        a0[r] <== state[idx][0] + intRc[r];
        sbP[r] = Sigma5();
        sbP[r].in <== a0[r];
        var sum = sbP[r].out + state[idx][1] + state[idx][2];
        state[idx+1][0] <== sbP[r].out + sum;
        state[idx+1][1] <== state[idx][1] + sum;
        state[idx+1][2] <== 2*state[idx][2] + sum;
        idx++;
    }

    // second half of full rounds
    signal ark2[4][3];
    component sbF2[4][3];
    for (var r = 0; r < 4; r++) {
        ark2[r][0] <== state[idx][0] + extRc[4+r][0];
        ark2[r][1] <== state[idx][1] + extRc[4+r][1];
        ark2[r][2] <== state[idx][2] + extRc[4+r][2];
        for (var j = 0; j < 3; j++) {
            sbF2[r][j] = Sigma5();
            sbF2[r][j].in <== ark2[r][j];
        }
        var s = sbF2[r][0].out + sbF2[r][1].out + sbF2[r][2].out;
        state[idx+1][0] <== sbF2[r][0].out + s;
        state[idx+1][1] <== sbF2[r][1].out + s;
        state[idx+1][2] <== sbF2[r][2].out + s;
        idx++;
    }

    out[0] <== state[idx][0];
    out[1] <== state[idx][1];
    out[2] <== state[idx][2];
}

// 2-to-1 hash: capacity=0, rate=[a,b]. Mirrors circomlib's Poseidon(2) output
// convention (state[0] after the permutation, capacity initialized to 0).
template Poseidon2Hash2() {
    signal input inputs[2];
    signal output out;

    component perm = Poseidon2Perm3();
    perm.in[0] <== 0;
    perm.in[1] <== inputs[0];
    perm.in[2] <== inputs[1];
    out <== perm.out[0];
}

// ---- t = 4 (3-to-1 compression, matches circomlib Poseidon(3)) ----

function POSEIDON2_T4_EXT_RC() {
    return ${arr2(T4_EXT_RC)};
}

function POSEIDON2_T4_INT_RC() {
    return ${arr1(T4_INT_RC)};
}

function POSEIDON2_T4_MAT() {
    return ${arr1(T4_MAT)};
}

template Poseidon2Perm4() {
    signal input in[4];
    signal output out[4];

    var extRc[8][4] = POSEIDON2_T4_EXT_RC();
    var intRc[56] = POSEIDON2_T4_INT_RC();
    var diag[4] = POSEIDON2_T4_MAT();

    signal state[8 + 56 + 1][4];

    // initial external mix: M4 block (near-MDS 4x4, no round constants)
    var t0_0 = in[0] + in[1];
    var t1_0 = in[2] + in[3];
    var t2_0 = 2*in[1] + t1_0;
    var t3_0 = 2*in[3] + t0_0;
    var t4_0 = 4*t1_0 + t3_0;
    var t5_0 = 4*t0_0 + t2_0;
    state[0][0] <== t3_0 + t5_0;
    state[0][1] <== t5_0;
    state[0][2] <== t2_0 + t4_0;
    state[0][3] <== t4_0;

    var idx = 0;
    signal ark1[4][4];
    component sbF1[4][4];
    for (var r = 0; r < 4; r++) {
        for (var j = 0; j < 4; j++) {
            ark1[r][j] <== state[idx][j] + extRc[r][j];
        }
        for (var j = 0; j < 4; j++) {
            sbF1[r][j] = Sigma5();
            sbF1[r][j].in <== ark1[r][j];
        }
        var a = sbF1[r][0].out;
        var b = sbF1[r][1].out;
        var c = sbF1[r][2].out;
        var d = sbF1[r][3].out;
        var t0 = a + b;
        var t1 = c + d;
        var t2 = 2*b + t1;
        var t3 = 2*d + t0;
        var t4 = 4*t1 + t3;
        var t5 = 4*t0 + t2;
        state[idx+1][0] <== t3 + t5;
        state[idx+1][1] <== t5;
        state[idx+1][2] <== t2 + t4;
        state[idx+1][3] <== t4;
        idx++;
    }

    signal a0[56];
    component sbP[56];
    for (var r = 0; r < 56; r++) {
        a0[r] <== state[idx][0] + intRc[r];
        sbP[r] = Sigma5();
        sbP[r].in <== a0[r];
        var sum = sbP[r].out + state[idx][1] + state[idx][2] + state[idx][3];
        state[idx+1][0] <== diag[0]*sbP[r].out + sum;
        state[idx+1][1] <== diag[1]*state[idx][1] + sum;
        state[idx+1][2] <== diag[2]*state[idx][2] + sum;
        state[idx+1][3] <== diag[3]*state[idx][3] + sum;
        idx++;
    }

    signal ark2[4][4];
    component sbF2[4][4];
    for (var r = 0; r < 4; r++) {
        for (var j = 0; j < 4; j++) {
            ark2[r][j] <== state[idx][j] + extRc[4+r][j];
        }
        for (var j = 0; j < 4; j++) {
            sbF2[r][j] = Sigma5();
            sbF2[r][j].in <== ark2[r][j];
        }
        var a = sbF2[r][0].out;
        var b = sbF2[r][1].out;
        var c = sbF2[r][2].out;
        var d = sbF2[r][3].out;
        var t0 = a + b;
        var t1 = c + d;
        var t2 = 2*b + t1;
        var t3 = 2*d + t0;
        var t4 = 4*t1 + t3;
        var t5 = 4*t0 + t2;
        state[idx+1][0] <== t3 + t5;
        state[idx+1][1] <== t5;
        state[idx+1][2] <== t2 + t4;
        state[idx+1][3] <== t4;
        idx++;
    }

    out[0] <== state[idx][0];
    out[1] <== state[idx][1];
    out[2] <== state[idx][2];
    out[3] <== state[idx][3];
}

// 3-to-1 hash: capacity=0, rate=[a,b,c]. Mirrors circomlib's Poseidon(3).
template Poseidon2Hash3() {
    signal input inputs[3];
    signal output out;

    component perm = Poseidon2Perm4();
    perm.in[0] <== 0;
    perm.in[1] <== inputs[0];
    perm.in[2] <== inputs[1];
    perm.in[3] <== inputs[2];
    out <== perm.out[0];
}
`;

const outPath = path.join(repoRoot, "circuits/bench/poseidon2.circom");
fs.writeFileSync(outPath, generated);
console.log("Regenerated", path.relative(repoRoot, outPath), `(${generated.length} bytes)`);
