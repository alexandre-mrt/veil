#!/usr/bin/env node
/**
 * gen-poseidon2-constants.mjs — extract the BN254 t=3 Poseidon2 parameters from the HorizenLabs
 * reference implementation and emit (a) a circom constants include and (b) a JSON file used by the
 * JS reference in poseidon2.mjs.
 *
 * Usage:
 *   git clone --depth 1 https://github.com/HorizenLabs/poseidon2 /path/to/hl-poseidon2
 *   node scripts/bench/hash-arity/gen-poseidon2-constants.mjs /path/to/hl-poseidon2
 *
 * Source file: plain_implementations/src/poseidon2/poseidon2_instance_bn256.rs
 * (t=3, d=5, R_F=8, R_P=56, internal diag-1 = [1,1,2]).
 */
import { readFileSync, writeFileSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";
import { execSync } from "child_process";

const here = dirname(fileURLToPath(import.meta.url));
const repo = process.argv[2];
if (!repo) { console.error("usage: gen-poseidon2-constants.mjs <hl-poseidon2 checkout>"); process.exit(1); }
const src = readFileSync(join(repo, "plain_implementations/src/poseidon2/poseidon2_instance_bn256.rs"), "utf8");
let commit = "unknown";
try { commit = execSync(`git -C ${repo} rev-parse HEAD`).toString().trim(); } catch {}

const rcBlock = src.slice(src.indexOf("pub static ref RC3"), src.indexOf("pub static ref POSEIDON2_BN256_PARAMS"));
const rows = [...rcBlock.matchAll(/vec!\[((?:\s*from_hex\("0x[0-9a-f]+"\),?\s*)+)\]/g)]
  .map(m => [...m[1].matchAll(/0x[0-9a-f]+/g)].map(x => BigInt(x[0])));
if (rows.length !== 64 || rows.some(r => r.length !== 3)) throw new Error(`expected 64x3 RCs, got ${rows.length}`);
const params = src.match(/Poseidon2Params::new\((\d+), (\d+), (\d+), (\d+),/).slice(1).map(Number);
if (params.join() !== "3,5,8,56") throw new Error(`unexpected params ${params}`);

const json = { source: "HorizenLabs/poseidon2 poseidon2_instance_bn256.rs", commit, t: 3, d: 5, RF: 8, RP: 56,
  diagM1: ["1", "1", "2"], RC: rows.map(r => r.map(String)) };
writeFileSync(join(here, "poseidon2_bn254_t3.json"), JSON.stringify(json, null, 1) + "\n");

const fmt = r => `[${r.map(String).join(", ")}]`;
const circom = `pragma circom 2.1.0;
// AUTO-GENERATED by gen-poseidon2-constants.mjs — do not edit.
// Source: HorizenLabs/poseidon2 @ ${commit}, poseidon2_instance_bn256.rs (t=3, d=5, R_F=8, R_P=56)
function POSEIDON2_T3_RC() {
    return [
        ${rows.map(fmt).join(",\n        ")}
    ];
}
`;
writeFileSync(join(here, "circuits", "poseidon2_constants.circom"), circom);
console.log(`wrote 64x3 round constants from ${commit}`);
