#!/usr/bin/env node
/**
 * gen-move-gas-test.mjs — emits contracts/tests/gas_bench_tests.move: Move unit tests that run
 * Veil's real Groth16 verification (real VKs, real proofs, from the valid-witness builders) so
 * `sui move test --statistics` reports raw, UNBUCKETED Move-VM gas for each verification step.
 *
 * Why: on-chain, Sui bills computation in coarse buckets (first bucket = 1000 gas units), so
 * gas-bench.ts cannot resolve costs below 1000 units. This script's output can.
 *
 * Usage (needs compiled circuits, see prove-latency.mjs header):
 *   node scripts/bench/gen-move-gas-test.mjs
 *   cd contracts && sui move test --build-env testnet --statistics gas_bench
 */
import { buildPoseidon } from "circomlibjs";
import { readFileSync, writeFileSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";
import * as snarkjs from "snarkjs";
import { WITNESS_BUILDERS, setPoseidonField, stringifyInputs } from "./witnesses.mjs";
import { proofToSuiBytes, publicInputsToSuiBytes, vkToSuiBytes } from "../src/proof-converter.ts";

const __dirname = dirname(fileURLToPath(import.meta.url));
const C = join(__dirname, "..", "..", "circuits");
const hex = (b) => Buffer.from(b).toString("hex");
const poseidon = await buildPoseidon();
setPoseidonField(poseidon.F);

const CIRCUITS = [
  { name: "transfer", dir: "build", verifier: "verify_transfer_proof" },
  { name: "withdraw", dir: "build-withdraw", verifier: "verify_withdraw_proof" },
  { name: "compliance", dir: "build-compliance", verifier: "verify_compliance_proof" },
];

let out = `// GENERATED by scripts/bench/gen-move-gas-test.mjs — do not edit by hand.
// Real VKs + real proofs; each test isolates one verification step so
// \`sui move test --build-env testnet --statistics gas_bench\` gives raw Move-VM gas per step.
#[test_only]
module veil::gas_bench_tests;

use sui::groth16;
use veil::verifier;

#[test]
fun gas_bench_control_empty() {}
`;

for (const c of CIRCUITS) {
  const w = stringifyInputs(WITNESS_BUILDERS[c.name](poseidon));
  const { proof, publicSignals } = await snarkjs.groth16.fullProve(
    w, join(C, c.dir, `${c.name}_js`, `${c.name}.wasm`), join(C, c.dir, `${c.name}_final.zkey`),
  );
  const vkJson = JSON.parse(readFileSync(join(C, c.dir, `${c.name}_vk.json`), "utf-8"));
  if (!(await snarkjs.groth16.verify(vkJson, publicSignals, proof))) throw new Error(`${c.name}: local verify failed`);
  const vk = hex(vkToSuiBytes(vkJson)), pf = hex(proofToSuiBytes(proof)), pi = hex(publicInputsToSuiBytes(publicSignals));
  const n = c.name;
  out += `
const ${n.toUpperCase()}_VK: vector<u8> = x"${vk}";
const ${n.toUpperCase()}_PROOF: vector<u8> = x"${pf}";
const ${n.toUpperCase()}_INPUTS: vector<u8> = x"${pi}";

// control: load the three byte vectors only
#[test]
fun gas_bench_${n}_a_load_only() {
    let _vk = ${n.toUpperCase()}_VK; let _p = ${n.toUpperCase()}_PROOF; let _i = ${n.toUpperCase()}_INPUTS;
}

// + parse proof points and public inputs
#[test]
fun gas_bench_${n}_b_parse_proof_inputs() {
    let _vk = ${n.toUpperCase()}_VK;
    let _p = groth16::proof_points_from_bytes(${n.toUpperCase()}_PROOF);
    let _i = groth16::public_proof_inputs_from_bytes(${n.toUpperCase()}_INPUTS);
}

// + prepare_verifying_key (what verifier.move does on EVERY call today)
#[test]
fun gas_bench_${n}_c_prepare_vk() {
    let vk = ${n.toUpperCase()}_VK;
    let _p = groth16::proof_points_from_bytes(${n.toUpperCase()}_PROOF);
    let _i = groth16::public_proof_inputs_from_bytes(${n.toUpperCase()}_INPUTS);
    let _pvk = groth16::prepare_verifying_key(&groth16::bn254(), &vk);
}

// full verifier::${c.verifier} exactly as pool.move / compliance.move call it
#[test]
fun gas_bench_${n}_d_full_verify() {
    let vk = ${n.toUpperCase()}_VK;
    assert!(verifier::${c.verifier}(&vk, ${n.toUpperCase()}_PROOF, ${n.toUpperCase()}_INPUTS));
}
`;
}
writeFileSync(join(__dirname, "..", "..", "contracts", "tests", "gas_bench_tests.move"), out);
console.log("wrote contracts/tests/gas_bench_tests.move");
process.exit(0); // snarkjs worker threads otherwise keep the process alive
