function sbox(x) {
  const x2 = mod(x * x);
  const x4 = mod(x2 * x2);
  return mod(x4 * x);
}

// External (full-round) linear layer, t=3: circ(2,1,1).
function extLinear(state) {
  const sum = mod(state[0] + state[1] + state[2]);
  return [mod(state[0] + sum), mod(state[1] + sum), mod(state[2] + sum)];
}

// Internal (partial-round) linear layer, t=3: J (all-ones) + diag(1,1,2).
function intLinear(state) {
  const sum = mod(state[0] + state[1] + state[2]);
  return [
    mod(state[0] * DIAG[0] + sum),
    mod(state[1] * DIAG[1] + sum),
    mod(state[2] * DIAG[2] + sum),
  ];
}

export function poseidon2Permutation3(input) {
  let state = extLinear(input);
  let r = 0;
  for (let i = 0; i < 4; i++, r++) {
    state = state.map((s, j) => mod(s + RC[r][j]));
    state = state.map(sbox);
    state = extLinear(state);
  }
  for (let i = 0; i < 56; i++, r++) {
    state[0] = mod(state[0] + RC[r][0]);
    state[0] = sbox(state[0]);
    state = intLinear(state);
  }
  for (let i = 0; i < 4; i++, r++) {
    state = state.map((s, j) => mod(s + RC[r][j]));
    state = state.map(sbox);
    state = extLinear(state);
  }
  return state;
}

